        r'\b(?:мо[йяеию]|моих|моём|моем|наши?|наша|наше|наших)\s+(?:личн\w*\s+)?'
        r'(?:путешеств|поезд|отпуск|жизн|семь|свадьб|истори|воспоминан|детств|каникул|юбиле|фотоальбом)|'
