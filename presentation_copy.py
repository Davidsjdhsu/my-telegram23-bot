def final_process_requested(data):
    """Recognize explicit final process diagrams, not arbitrary final illustrations."""
    for field in ('topic', 'extra', 'user_text'):
        for clause in re.split(r'[.!?;\n]', str(data.get(field) or '').casefold().replace('ё', 'е')):
            if re.search(r'не\s+(?:нужн\w*|добавля\w*|дела\w*|показыва\w*)|do not|without', clause):
                continue
            final = re.search(r'последн\w*\s+слайд|финальн\w*\s+слайд|в\s+конце|итогов\w*|final\s+slide|last\s+slide|at the end', clause)
            diagram = re.search(r'схем\w*|покаж\w*.{0,40}(?:весь|все|цел\w*)\s+процесс|diagram|flowchart', clause)
            process = re.search(r'процесс|этап|последовательн|цикл|круговорот|process|steps|cycle|flowchart', clause)
            if final and diagram and process:
                return True
    return False

