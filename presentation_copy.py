def photo_sources(assets):
    """Expose only bounded evidence, never file paths or image bytes, to text models."""
    return [{'slide':i+1, 'caption':a.get('caption',''),
             'visible':a.get('description',''), 'description_available':bool(a.get('description'))}
            for i,a in enumerate(assets) if a and a.get('origin')=='user']


